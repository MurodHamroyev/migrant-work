from django.core.management.base import BaseCommand
from core.models import Vacancy, Warehouse

DEMO = [
    ("Упаковщик на склад", "Подольск", "ул. Складская 5", 65000, "5/2", 8, "Упаковка и сортировка товаров на крупном складе маркетплейса. Работа несложная, обучение в первый день."),
    ("Сборщик заказов", "Химки", "мкр. Подрезково 1", 70000, "2/2", 12, "Сборка заказов для интернет-магазина по накладным. Сканирование штрихкодов, упаковка."),
    ("Разнорабочий на производстве", "Дмитров", "ул. Профсоюзная 10", 60000, "5/2", 8, "Помощь на производственной линии: упаковка готовой продукции, погрузка-разгрузка, поддержание чистоты."),
    ("Комплектовщик на склад", "Электросталь", "ул. Машиностроителей 3", 75000, "3/3", 11, "Комплектация партий товара по заявкам, проверка качества, работа с терминалом сбора данных."),
]


class Command(BaseCommand):
    help = "Создаёт демо-склады и вакансии"

    def handle(self, *a, **kw):
        if Vacancy.objects.exists():
            return self.stdout.write("Вакансии уже есть")
        for t, c, ad, s, sc, h, d in DEMO:
            w = Warehouse.objects.create(name=f"Склад {c}", city=c, address=ad)
            Vacancy.objects.create(title=t, warehouse=w, salary=s, schedule=sc, shift_hours=h, description=d,
                                   requirements="Документы, удостоверяющие личность", conditions="Выплаты два раза в месяц")
        self.stdout.write("Готово: 4 склада и 4 вакансии")
